#include <stdio.h>

int main(void)
{
    // This program tests different data types and operations.

    int wholeNumber = 10;
    double decimalNumber = 3.14;
    char letter = 'A';

    printf("Whole number: %d\n", wholeNumber);
    printf("Decimal number: %.2f\n", decimalNumber);
    printf("Character: %c\n", letter);
    printf("Sum: %d\n", wholeNumber + 5);

    return 0;
}