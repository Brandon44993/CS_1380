#include <stdio.h>

int main(void)
{
    // Variables store values that the program uses.
    int first_number = 10;
    int second_number = 5;

    // Calculate the sum of the two numbers.
    int sum = first_number + second_number;

    printf("First number: %d\n", first_number);
    printf("Second number: %d\n", second_number);
    printf("Sum: %d\n", sum);

    return 0;
}